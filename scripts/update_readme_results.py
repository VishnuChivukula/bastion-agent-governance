"""Rewrite the README results table from `evals/results/latest.json` (FR-60).

The table holds only values that are the same on every machine (counts, rates, pass/fail), so
CI can check that the committed README matches a fresh `make eval`.
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
START, END = "<!-- RESULTS:START -->", "<!-- RESULTS:END -->"


def render(result: dict) -> str:
    counts, metrics = result["counts"], result["metrics"]
    checks = {row["key"]: row for row in result["thresholds"]}

    def mark(key: str) -> str:
        return "pass" if checks[key]["pass"] else "**FAIL**"

    def count(suite: str) -> str:
        entry = counts[suite]
        return f"{entry['passed']} / {entry['total']}"

    p95_limit = checks["gateway_overhead_p95_ms"]["threshold"]
    rows = [
        ("Red-team: attacks that must be blocked", count("redteam"), "100%",
         mark("redteam_must_block_rate")),
        ("Benign: ordinary work that must go through", count("benign"), "≥ 95%",
         mark("benign_pass_rate")),
        ("Assessor: risk tier matches the gold tier", count("assessor"), "≥ 80%",
         mark("assessor_tier_accuracy")),
        ("Reviewer: seeded wrong assessments caught",
         f"{metrics['reviewer_seeded_catches']} / {metrics['reviewer_seeded_total']}", "≥ 2",
         mark("reviewer_seeded_catches")),
        ("Structured output validity", f"{metrics['structured_output_validity']:.0%}", "100%",
         mark("structured_output_validity")),
        ("Audit chain verifies after a clean run",
         "yes" if metrics["audit_verify_clean_run"] else "no", "yes",
         mark("audit_verify_clean_run")),
        ("Gateway overhead p95 (excluding the tool)", f"under {p95_limit:g} ms"
         if checks["gateway_overhead_p95_ms"]["pass"] else f"over {p95_limit:g} ms",
         f"< {p95_limit:g} ms", mark("gateway_overhead_p95_ms")),
    ]  # fmt: skip
    lines = [
        "| Suite | Result | Threshold | Gate |",
        "|---|---|---|---|",
        *(f"| {a} | {b} | {c} | {d} |" for a, b, c, d in rows),
        "",
        f"Overall gate: **{'PASS' if result['passed'] else 'FAIL'}**. Generated by `make eval` "
        "in replay mode (no model calls); CI fails if a threshold is breached or if this table "
        "is out of date. Scenario definitions: [`evals/`](evals/); design: "
        "[`docs/EVALS.md`](docs/EVALS.md). Gold tiers for the assessor suite are unverified "
        "starting points ([`docs/VERIFY.md`](docs/VERIFY.md)).",
    ]
    return "\n".join(lines)


def update(readme: Path, results: Path) -> bool:
    """Returns True if the README changed."""
    text = readme.read_text(encoding="utf-8")
    start, end = text.index(START) + len(START), text.index(END)
    table = render(json.loads(results.read_text(encoding="utf-8")))
    updated = f"{text[:start]}\n{table}\n{text[end:]}"
    if updated == text:
        return False
    readme.write_text(updated, encoding="utf-8")
    return True


def main() -> int:
    changed = update(ROOT / "README.md", ROOT / "evals" / "results" / "latest.json")
    print("README results table " + ("updated" if changed else "already up to date"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
